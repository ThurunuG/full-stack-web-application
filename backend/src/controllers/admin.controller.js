const crypto = require('crypto');
const bcrypt = require('bcryptjs');
const prisma = require('../config/prisma');

/**
 * Generate a strong, readable random password
 */
const generateRandomPassword = (length = 12) => {
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!@#$%^&*';
  let password = '';
  const bytes = crypto.randomBytes(length);
  for (let i = 0; i < length; i++) {
    password += chars[bytes[i] % chars.length];
  }
  return password;
};

/**
 * Create a new admin account (Protected - ADMIN only)
 * Auto-generates random password, hashes it, and returns it in response
 */
const createAdmin = async (req, res) => {
  try {
    const { email } = req.body;

    // Check if email already exists
    const existingUser = await prisma.user.findUnique({
      where: { email: email.toLowerCase() },
    });

    if (existingUser) {
      return res.status(409).json({
        success: false,
        message: 'A user with this email address already exists.',
      });
    }

    // Auto-generate random password
    const autoGeneratedPassword = generateRandomPassword(12);

    // Hash the password
    const hashedPassword = await bcrypt.hash(autoGeneratedPassword, 10);

    // Create admin user
    const newAdmin = await prisma.user.create({
      data: {
        email: email.toLowerCase(),
        password: hashedPassword,
        role: 'ADMIN',
      },
      select: {
        id: true,
        email: true,
        role: true,
        createdAt: true,
      },
    });

    return res.status(201).json({
      success: true,
      message: 'New admin account created successfully.',
      admin: newAdmin,
      autoGeneratedPassword, // Returned once so the initiating admin can copy and share it
    });
  } catch (error) {
    console.error('Admin creation error:', error);
    return res.status(500).json({
      success: false,
      message: 'Internal server error while creating admin account.',
    });
  }
};

/**
 * List all admin accounts (Protected - ADMIN only)
 */
const getAllAdmins = async (req, res) => {
  try {
    const admins = await prisma.user.findMany({
      where: { role: 'ADMIN' },
      select: {
        id: true,
        email: true,
        role: true,
        createdAt: true,
      },
      orderBy: { createdAt: 'desc' },
    });

    return res.status(200).json({
      success: true,
      admins,
    });
  } catch (error) {
    console.error('Get admins error:', error);
    return res.status(500).json({
      success: false,
      message: 'Internal server error while fetching admin list.',
    });
  }
};

module.exports = {
  createAdmin,
  getAllAdmins,
};
